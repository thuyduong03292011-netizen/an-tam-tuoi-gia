# 🌿 An Tâm Tuổi Già - Ứng Dụng AI Quản Lý Sức Khỏe Người Cao Tuổi

Dự án tham gia cuộc thi Khởi nghiệp Sáng tạo. Ứng dụng đóng vai trò như một trợ lý điều dưỡng ảo giao tiếp bằng giọng nói tiếng Việt, giúp người cao tuổi quản lý lịch uống thuốc, theo dõi chỉ số sức khỏe và kết nối cảnh báo khẩn cấp tới con cái.

## ✨ Tính năng chính (Phiên bản MVP)
- **Giao diện siêu tối giản:** Chữ kích thước lớn, nút bấm rõ ràng dành riêng cho người lớn tuổi.
- **Trợ lý giọng nói AI:** Nghe hiểu tiếng Việt và phản hồi bằng giọng nói tự nhiên (tích hợp Gemini API).
- **Nhắc lịch uống thuốc thông minh:** Thông báo bằng âm thanh và xác nhận đã uống thuốc.
- **Nút khẩn cấp SOS:** Gửi cảnh báo kèm vị trí GPS ngay lập tức cho người thân.
- **Góc Con Cái / Giám Hộ:** Theo dõi trạng thái uống thuốc và chỉ số huyết áp theo thời gian thực.

## 🚀 Hướng dẫn chạy dự án
1. Tải mã nguồn về máy hoặc bật **GitHub Pages** trong phần `Settings > Pages` để chạy trực tiếp trên điện thoại.
2. Mở tệp `app.js` và dán mã **Gemini API Key** của bạn (lấy miễn phí tại Google AI Studio) vào biến `GEMINI_API_KEY`.
3. Mở `index.html` trên trình duyệt Chrome hoặc Safari và cấp quyền sử dụng Micro.

